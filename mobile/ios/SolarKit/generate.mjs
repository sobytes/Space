/**
 * Emits the Standish element tables as Swift, from the TypeScript the website uses.
 *
 * Four hundred numbers transcribed by hand is four hundred chances to put a digit in the wrong
 * column, and a wrong element does not throw: it renders as a planet in a plausible but wrong
 * place. Importing the parsed tables and printing them means the Swift and TypeScript clients
 * are reading the same figures by construction, and a change to the tables reaches both with
 * one command.
 *
 * Run from the repository root:  node mobile/ios/SolarKit/generate.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const { SHORT_SPAN, LONG_SPAN, PLANET_IDS } = await import("../../../engine/src/data/planets.ts");
const time = await import("../../../engine/src/time.ts");
const { ACCURACY } = await import("../../../engine/src/data/ephemeris-accuracy.ts");
const { BODY_CONTRACTS } = await import("../../../engine/src/bodies/registry.ts");
const { obliquityToOrbitDeg } = await import("../../../engine/src/rotation.ts");
const { jdTdb, J2000_JD } = await import("../../../engine/src/time.ts");

const num = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));

function elementSet(set) {
  return [
    `semiMajorAxisAu: ${num(set.semiMajorAxisAu)}`,
    `eccentricity: ${num(set.eccentricity)}`,
    `inclinationDeg: ${num(set.inclinationDeg)}`,
    `meanLongitudeDeg: ${num(set.meanLongitudeDeg)}`,
    `longitudeOfPerihelionDeg: ${num(set.longitudeOfPerihelionDeg)}`,
    `longitudeOfAscendingNodeDeg: ${num(set.longitudeOfAscendingNodeDeg)}`,
  ].join(", ");
}

function model(name, m) {
  const entries = PLANET_IDS.map((id) => {
    const e = m.elements[id];
    const extra = e.longPeriodTerms
      ? `LongPeriodTerms(b: ${num(e.longPeriodTerms.b)}, c: ${num(e.longPeriodTerms.c)}, ` +
        `s: ${num(e.longPeriodTerms.s)}, f: ${num(e.longPeriodTerms.f)})`
      : "nil";
    return `        .${id}: PlanetElements(
            atJ2000: ElementSet(${elementSet(e.atJ2000)}),
            ratePerCentury: ElementSet(${elementSet(e.ratePerCentury)}),
            longPeriodTerms: ${extra}
        )`;
  }).join(",\n");

  const errors = PLANET_IDS.map((id) => {
    const q = m.quotedError[id];
    return `        .${id}: QuotedError(longitudeArcsec: ${num(q.longitude)}, ` +
      `latitudeArcsec: ${num(q.latitude)}, distanceKm: ${num(q.distanceKm)})`;
  }).join(",\n");

  return `public let ${name} = EphemerisModel(
    id: "${m.id}",
    validFromYear: ${m.validFromYear},
    validToYear: ${m.validToYear},
    elements: [
${entries}
    ],
    quotedError: [
${errors}
    ]
)`;
}

const out = `// Generated by mobile/ios/SolarKit/generate.mjs from engine/src/data/planets.ts.
// Do not edit by hand. Re-run the generator after changing the tables.
//
// Source of the figures: https://ssd.jpl.nasa.gov/planets/approx_pos.html
// (E.M. Standish and J.G. Williams, reformatted by JPL/Caltech), mean ecliptic and equinox
// of J2000. \`quotedError\` is JPL's own published accuracy table, not a tolerance chosen here.

${model("shortSpan", SHORT_SPAN)}

${model("longSpan", LONG_SPAN)}
`;

const target = fileURLToPath(
  new URL("./Sources/SolarKit/Generated/StandishTables.swift", import.meta.url),
);
writeFileSync(target, out);
console.log(`wrote ${out.split("\n").length} lines to ${target}`);

/**
 * The leap-second table, emitted rather than retyped for the same reason as the elements.
 * It is sampled through the engine's own accessor so the Swift copy is the table the
 * TypeScript actually uses, not a parallel transcription of the IERS bulletin.
 */
const SAMPLE_START = 2441317.5; // 1972-01-01
const steps = [];
let previous = null;
for (let jd = SAMPLE_START; jd <= 2461000.5; jd += 1) {
  const offset = time.taiMinusUtcSeconds(time.jdUtc(jd));
  if (offset !== previous) {
    steps.push({ jd, offset });
    previous = offset;
  }
}

const leap = `// Generated by mobile/ios/SolarKit/generate.mjs from engine/src/time.ts.
// Do not edit by hand.
//
// TAI minus UTC, as a step function of UTC Julian date. ${steps.length} entries, the last
// stepping to ${steps[steps.length - 1].offset} s. There has been no insertion since then, and
// the IERS may announce another at any time, so a client that hardcodes the current value is
// correct only until it is not.

public let leapSecondSteps: [(fromJdUtc: Double, taiMinusUtcSeconds: Double)] = [
${steps.map((s) => `    (fromJdUtc: ${s.jd}, taiMinusUtcSeconds: ${num(s.offset)})`).join(",\n")}
]
`;
const envelopes = `// Generated by mobile/ios/SolarKit/generate.mjs from
// engine/src/data/ephemeris-accuracy.ts. Do not edit by hand.
//
// How far outside JPL's nominal error each body is allowed to land. JPL calls its figures
// nominal errors, not bounds, so asserting every epoch inside them is the wrong test and fails
// on six of eight bodies with a correct implementation. The gate gates RMS against nominal
// plus a per-epoch ceiling, both scaled by these. Any factor above 1 carries a written
// justification in the TypeScript source. See contracts/ephemeris-accuracy.

public struct AccuracyEnvelope: Sendable {
    public let rmsFactor: Double
    public let maxFactor: Double
}

public let accuracyEnvelopes: [Planet: AccuracyEnvelope] = [
${PLANET_IDS.map((id) => `    .${id}: AccuracyEnvelope(rmsFactor: ${num(ACCURACY[id].rmsFactor)}, maxFactor: ${num(ACCURACY[id].maxFactor)})`).join(",\n")}
]
`;
writeFileSync(
  fileURLToPath(new URL("./Sources/SolarKit/Generated/AccuracyEnvelopes.swift", import.meta.url)),
  envelopes,
);
console.log("wrote accuracy envelopes");

/**
 * The whole body registry, all 32 contracts, emitted as Swift.
 *
 * Not a subset and not a simplification. The registry is the single place the project is
 * allowed to assert anything about a body, and a port that carries only the fields its current
 * screen happens to use will quietly disagree with the website the first time a screen grows.
 */
const esc = (t) => String(t).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
const optStr = (v) => (typeof v === "string" ? `"${esc(v)}"` : "nil");

function ephemeris(e) {
  if (e.kind === "fixed-at-barycentre") return `.fixedAtBarycentre(note: "${esc(e.note)}")`;
  if (e.kind === "standish-elements") return `.standishElements(planet: .${e.planet})`;
  return `.meanElementsAboutParent(MeanElements(
            semiMajorAxisM: ${num(e.semiMajorAxisM)},
            eccentricity: ${num(e.eccentricity)},
            inclinationDeg: ${num(e.inclinationDeg)},
            argumentOfPeriapsisDeg: ${num(e.argumentOfPeriapsisDeg)},
            ascendingNodeDeg: ${num(e.ascendingNodeDeg)},
            meanAnomalyAtEpochDeg: ${num(e.meanAnomalyAtEpochDeg)},
            epochJd: ${num(e.epochJd)},
            periodDays: ${num(e.periodDays)},
            referencePlane: .${{ "parent-equator": "parentEquator", laplace: "laplace", ecliptic: "ecliptic" }[e.referencePlane]},
            source: "${esc(e.source)}"
        ))`;
}

function contract(id, c) {
  const a = c.appearance;
  return `    .${id}: BodyContract(
        id: .${id},
        displayName: "${esc(c.displayName)}",
        kind: .${c.kind},
        parent: ${c.parent ? `.${c.parent}` : "nil"},
        ephemeris: ${ephemeris(c.ephemeris)},
        rotation: RotationalElements(
            poleRaDeg: ${num(c.rotation.poleRaDeg)},
            poleRaRateDegPerCentury: ${num(c.rotation.poleRaRateDegPerCentury)},
            poleDecDeg: ${num(c.rotation.poleDecDeg)},
            poleDecRateDegPerCentury: ${num(c.rotation.poleDecRateDegPerCentury)},
            primeMeridianDeg: ${num(c.rotation.primeMeridianDeg)},
            rotationRateDegPerDay: ${num(c.rotation.rotationRateDegPerDay)},
            source: "${esc(c.rotation.source)}"
        ),
        isSynchronous: ${c.rotationRegime === "synchronous"},
        gm: ${num(c.gm)},
        equatorialRadiusM: ${num(c.equatorialRadiusM)},
        polarRadiusM: ${num(c.polarRadiusM)},
        siderealRotationDays: ${num(c.siderealRotationDays)},
        obliquityToOrbitDeg: ${num(c.obliquityToOrbitDeg)},
        geometricAlbedo: ${num(c.geometricAlbedo)},
        meanTemperatureK: ${num(c.meanTemperatureK)},
        confirmedMoons: ${c.confirmedMoons},
        atmosphere: ${c.atmosphere
          ? `Atmosphere(
            surfacePressurePa: ${c.atmosphere.surfacePressurePa === null ? "nil" : num(c.atmosphere.surfacePressurePa)},
            scaleHeightM: ${num(c.atmosphere.scaleHeightM)},
            composition: [${Object.entries(c.atmosphere.composition).map(([g, f]) => `("${g}", ${num(f)})`).join(", ")}],
            source: "${esc(c.atmosphere.source)}"
        )`
          : "nil"},
        appearance: Appearance(
            albedoTextureId: ${optStr(a.albedoTextureId)},
            nightTextureId: ${optStr(a.nightTextureId)},
            cloudTextureId: ${optStr(a.cloudTextureId)},
            ringSystem: ${a.ringSystem
              ? `RingSystem(innerRadiusM: ${num(a.ringSystem.innerRadiusM)}, outerRadiusM: ${num(a.ringSystem.outerRadiusM)}, textureId: "${a.ringSystem.textureId}", opacity: ${num(a.ringSystem.opacity)})`
              : "nil"},
            tintHex: "${a.tint}",
            isEmissive: ${a.emissive}
        ),
        education: Education(
            oneLine: "${esc(c.education.oneLine)}",
            whyItMatters: "${esc(c.education.whyItMatters)}",
            facts: [${c.education.facts.map((f) => `"${esc(f)}"`).join(",\n                ")}]
        ),
        knownDiscrepancies: [${c.knownDiscrepancies.map((d) => `
            KnownDiscrepancy(field: "${esc(d.field)}", summary: "${esc(d.summary)}", preferred: "${esc(d.preferred)}", rejected: "${esc(d.rejected)}")`).join(",")}
        ]
    )`;
}

const ids = Object.keys(BODY_CONTRACTS);
const bodies = `// Generated by mobile/ios/SolarKit/generate.mjs from engine/src/bodies/registry.ts.
// Do not edit by hand. Re-run the generator after changing the registry.
//
// All ${ids.length} bodies, with every field the contract carries. A port that copies only the
// fields its current screen uses disagrees with the website the first time a screen grows.

public enum BodyId: String, CaseIterable, Sendable {
    case ${ids.join(", ")}
}

public enum BodyKind: String, Sendable { case star, planet, moon }

public enum ReferencePlane: Sendable { case parentEquator, laplace, ecliptic }

public struct MeanElements: Sendable {
    public let semiMajorAxisM: Double
    public let eccentricity: Double
    public let inclinationDeg: Double
    public let argumentOfPeriapsisDeg: Double
    public let ascendingNodeDeg: Double
    public let meanAnomalyAtEpochDeg: Double
    public let epochJd: Double
    public let periodDays: Double
    public let referencePlane: ReferencePlane
    public let source: String
}

public enum EphemerisSource: Sendable {
    case fixedAtBarycentre(note: String)
    case standishElements(planet: Planet)
    case meanElementsAboutParent(MeanElements)
}

/// IAU rotational elements. W1 negative means retrograde. See contracts/rotation-and-poles.
public struct RotationalElements: Sendable {
    public let poleRaDeg: Double
    public let poleRaRateDegPerCentury: Double
    public let poleDecDeg: Double
    public let poleDecRateDegPerCentury: Double
    public let primeMeridianDeg: Double
    public let rotationRateDegPerDay: Double
    public let source: String
}

public struct RingSystem: Sendable {
    public let innerRadiusM: Double
    public let outerRadiusM: Double
    public let textureId: String
    public let opacity: Double
}

public struct Appearance: Sendable {
    public let albedoTextureId: String?
    public let nightTextureId: String?
    public let cloudTextureId: String?
    public let ringSystem: RingSystem?
    public let tintHex: String
    public let isEmissive: Bool
}

public struct Atmosphere: Sendable {
    public let surfacePressurePa: Double?
    public let scaleHeightM: Double
    /// Mole fractions, in the registry's order.
    public let composition: [(String, Double)]
    public let source: String
}

public struct Education: Sendable {
    public let oneLine: String
    public let whyItMatters: String
    public let facts: [String]
}

public struct KnownDiscrepancy: Sendable {
    public let field: String
    public let summary: String
    public let preferred: String
    public let rejected: String
}

public struct BodyContract: Sendable {
    public let id: BodyId
    public let displayName: String
    public let kind: BodyKind
    public let parent: BodyId?
    public let ephemeris: EphemerisSource
    public let rotation: RotationalElements
    /// Satellites only. A planet is always independent of its orbit.
    public let isSynchronous: Bool
    public let gm: Double
    public let equatorialRadiusM: Double
    public let polarRadiusM: Double
    public let siderealRotationDays: Double
    public let obliquityToOrbitDeg: Double
    public let geometricAlbedo: Double
    public let meanTemperatureK: Double
    public let confirmedMoons: Int
    public let atmosphere: Atmosphere?
    public let appearance: Appearance
    public let education: Education
    public let knownDiscrepancies: [KnownDiscrepancy]
}

public let bodyContracts: [BodyId: BodyContract] = [
${ids.map((id) => contract(id, BODY_CONTRACTS[id])).join(",\n")}
]

/// Registry order, which groups each planet with its moons.
public let bodyIds: [BodyId] = [${ids.map((i) => `.${i}`).join(", ")}]

public func childrenOf(_ id: BodyId) -> [BodyId] {
    bodyIds.filter { bodyContracts[$0]?.parent == id }
}

/// How far a body's satellite system reaches, metres, or nil if it has none here. Apoapsis,
/// not the semi-major axis: Phoebe's eccentricity of 0.16 puts it 1.6 million km further out.
public func satelliteSystemRadiusM(_ id: BodyId) -> Double? {
    var furthest = 0.0
    for child in childrenOf(id) {
        if case let .meanElementsAboutParent(e) = bodyContracts[child]!.ephemeris {
            furthest = max(furthest, e.semiMajorAxisM * (1 + e.eccentricity))
        }
    }
    return furthest > 0 ? furthest : nil
}

/// The planet a Planet case corresponds to in the body registry.
public func bodyId(for planet: Planet) -> BodyId { BodyId(rawValue: planet.rawValue)! }
`;
writeFileSync(
  fileURLToPath(new URL("./Sources/SolarKit/Generated/Bodies.swift", import.meta.url)),
  bodies,
);
console.log(`wrote ${ids.length} body contracts`);

const leapTarget = fileURLToPath(
  new URL("./Sources/SolarKit/Generated/LeapSeconds.swift", import.meta.url),
);
writeFileSync(leapTarget, leap);
console.log(`wrote ${steps.length} leap-second steps to ${leapTarget}`);
