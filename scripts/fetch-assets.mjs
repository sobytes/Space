/**
 * Downloads planetary textures and elevation data by tier, then regenerates the attribution
 * file from what actually landed on disk.
 *
 * The attribution is generated rather than hand-written because several of these sources
 * require visible credit as a licence condition, and a hand-written credits page drifts from
 * the assets the moment anyone adds one. Generating it means the page cannot be wrong.
 *
 *   node scripts/fetch-assets.mjs 1        # tier 1 only
 *   node scripts/fetch-assets.mjs 1 2      # tiers 1 and 2
 *   node scripts/fetch-assets.mjs --list   # show what each tier costs, download nothing
 */

import { createWriteStream } from "node:fs";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";

const OUT_DIR = "public/textures";
const MANIFEST = "scripts/assets.manifest.json";
const USER_AGENT = "solar-system-sim/0.1 (educational simulation; asset fetch)";

const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));
const args = process.argv.slice(2);
const listOnly = args.includes("--list");
const tiers = args.filter((a) => /^\d+$/.test(a)).map(Number);
const wanted = tiers.length > 0 ? tiers : [1];

const selected = manifest.assets.filter((a) => wanted.includes(a.tier));

function human(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 ** 2) return `${(bytes / 1024).toFixed(1)} KB`;
  if (bytes < 1024 ** 3) return `${(bytes / 1024 ** 2).toFixed(1)} MB`;
  return `${(bytes / 1024 ** 3).toFixed(2)} GB`;
}

async function headSize(url) {
  try {
    const res = await fetch(url, { method: "HEAD", headers: { "User-Agent": USER_AGENT } });
    const len = res.headers.get("content-length");
    return { ok: res.ok, status: res.status, bytes: len ? Number(len) : null };
  } catch (err) {
    return { ok: false, status: 0, bytes: null, error: err.message };
  }
}

if (listOnly) {
  console.log("tier  id                      size        status  url");
  for (const asset of manifest.assets) {
    const probe = await headSize(asset.url);
    const size = probe.bytes === null ? "unknown" : human(probe.bytes);
    console.log(
      `  ${asset.tier}   ${asset.id.padEnd(22)} ${size.padStart(10)}  ${String(probe.status).padStart(5)}   ${asset.url}`,
    );
  }
  process.exit(0);
}

await mkdir(OUT_DIR, { recursive: true });

const results = [];
for (const asset of selected) {
  const target = `${OUT_DIR}/${asset.file}`;
  try {
    const existing = await stat(target);
    if (existing.size > 0) {
      console.log(`  skip  ${asset.id.padEnd(22)} already present, ${human(existing.size)}`);
      results.push({ ...asset, bytes: existing.size, state: "present" });
      continue;
    }
  } catch {
    // not downloaded yet
  }

  const res = await fetch(asset.url, { headers: { "User-Agent": USER_AGENT } });
  if (!res.ok || !res.body) {
    console.log(`  FAIL  ${asset.id.padEnd(22)} HTTP ${res.status}`);
    results.push({ ...asset, bytes: 0, state: `failed HTTP ${res.status}` });
    continue;
  }

  await pipeline(Readable.fromWeb(res.body), createWriteStream(target));
  const written = await stat(target);
  console.log(`  ok    ${asset.id.padEnd(22)} ${human(written.size).padStart(10)}  -> ${target}`);
  results.push({ ...asset, bytes: written.size, state: "downloaded" });
}

const landed = results.filter((r) => r.bytes > 0);
const usedLicences = [...new Set(landed.map((r) => r.licence))];

const attribution = `# Attribution

Generated by \`scripts/fetch-assets.mjs\` from \`scripts/assets.manifest.json\`. Do not edit by
hand; it is regenerated from the assets actually on disk so it cannot drift out of date.

Last generated ${new Date().toISOString()}. ${landed.length} assets, ${human(landed.reduce((s, r) => s + r.bytes, 0))} total.

## Licences in use

${usedLicences
  .map((key) => {
    const l = manifest.licences[key];
    return `### ${l.name}\n\n${l.requires}\n\nTerms: ${l.url}\n`;
  })
  .join("\n")}
## Assets

| Asset | File | Size | Licence | Source |
|---|---|---|---|---|
${landed
  .map(
    (r) =>
      `| ${r.id} | \`${r.file}\` | ${human(r.bytes)} | ${manifest.licences[r.licence].name} | ${r.url} |`,
  )
  .join("\n")}

## Deliberately not used

${manifest.excluded.map((e) => `- **${e.source}**: ${e.reason}`).join("\n")}

## Orbital and physical data

Planetary positions are computed in-app from the Keplerian element tables published at
https://ssd.jpl.nasa.gov/planets/approx_pos.html. Rotational elements follow the IAU Working
Group on Cartographic Coordinates and Rotational Elements, as encoded in NASA NAIF's
\`pck00011.tpc\`. Physical parameters come from https://ssd.jpl.nasa.gov/planets/phys_par.html
and the NASA Planetary Fact Sheet.

Validation compares against JPL Horizons (https://ssd.jpl.nasa.gov/horizons/), queried at
development time only. Per JPL's API policy their endpoints are never called from the browser.

Data courtesy NASA/JPL-Caltech. This project is not endorsed by NASA or JPL.
`;

await writeFile("public/ATTRIBUTION.md", attribution);
console.log(`\n${landed.length} assets on disk, ${human(landed.reduce((s, r) => s + r.bytes, 0))}.`);
console.log("public/ATTRIBUTION.md regenerated.");

const failed = results.filter((r) => r.bytes === 0);
if (failed.length > 0) {
  console.log(`\n${failed.length} failed:`);
  for (const f of failed) console.log(`  ${f.id}: ${f.state}  ${f.url}`);
  process.exit(1);
}
